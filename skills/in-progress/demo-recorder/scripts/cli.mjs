#!/usr/bin/env node
// demo-recorder CLI.
//   node cli.mjs validate <scenario.mjs> [--var k=v]
//   node cli.mjs dry|record <scenario.mjs> [--var k=v] [--space <id>] [--out <dir>]
//   node cli.mjs finish <spaceId>
import { spawnSync, execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { normalize } from "./recorder/schema.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url)).replace(/\\/g, "/");
import os from "node:os";
const OUT_ROOT = (process.env.DEMO_RECORDER_OUT || path.join(os.homedir(), "ego", "demo-recorder-out")).replace(/\\/g, "/");

function parseArgs(argv) {
  const pos = [];
  const opt = { vars: {} };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--var") { const [k, ...v] = argv[++i].split("="); opt.vars[k] = v.join("="); }
    else if (a === "--space") opt.space = Number(argv[++i]);
    else if (a === "--out") opt.out = argv[++i];
    else if (a === "--from") opt.from = argv[++i];
    else pos.push(a);
  }
  return { pos, opt };
}

function insideGit(dir) {
  let d = path.resolve(dir);
  while (!fs.existsSync(d) && path.dirname(d) !== d) d = path.dirname(d);
  while (true) {
    if (fs.existsSync(path.join(d, ".git"))) return d;
    const up = path.dirname(d);
    if (up === d) return null;
    d = up;
  }
}

function stamp() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, "0");
  return `${d.getFullYear()}${p(d.getMonth() + 1)}${p(d.getDate())}-${p(d.getHours())}${p(d.getMinutes())}${p(d.getSeconds())}`;
}

function runEgo(file) {
  const url = pathToFileURL(file).href;
  const r = spawnSync(`ego-browser nodejs -e "await import('${url}')"`, { shell: true, stdio: "inherit" });
  return r.status ?? 1;
}

async function loadScenario(file, vars) {
  const mod = await import(pathToFileURL(path.resolve(file)).href);
  return normalize(mod.default, vars);
}

const { pos, opt } = parseArgs(process.argv.slice(2));
const [cmd, target] = pos;

if (cmd === "validate" || cmd === "dry" || cmd === "record") {
  if (!target) { console.error("시나리오 파일을 주세요"); process.exit(2); }
  const scPath = path.resolve(target).replace(/\\/g, "/");
  const { scenario, errors, warnings } = await loadScenario(scPath, opt.vars);
  for (const w of warnings) console.log("경고:", w);
  for (const e of errors) console.log("오류:", e);
  if (errors.length) process.exit(1);
  if (cmd === "validate") {
    const est = scenario.steps.reduce((a, s) => a + s.hold, 0) / 1000;
    console.log(`통과: 단계 ${scenario.steps.length}개, 멈춤 합계 약 ${est.toFixed(0)}초 (동작·스크롤 시간 제외)`);
    process.exit(0);
  }
  const out = (opt.out || `${OUT_ROOT}/${scenario.name}-${stamp()}${cmd === "dry" ? "-dry" : ""}`).replace(/\\/g, "/");
  const repo = insideGit(out);
  if (repo) {
    // inside a repo is fine only when git ignores the folder (e.g. <repo>/.demo-recorder/out/…): frames never get committed
    let ignored = false;
    try { execFileSync("git", ["-C", repo, "check-ignore", "-q", out], { stdio: "ignore" }); ignored = true; } catch {}
    if (!ignored) { console.error(`출력 폴더가 git 작업 폴더(${repo}) 안인데 git 제외가 아닙니다. .gitignore에 넣은 폴더나 저장소 밖을 쓰세요`); process.exit(2); }
  }
  fs.mkdirSync(out, { recursive: true });
  const runFile = `${out}/run.mjs`;
  // --var values (real names for redaction) go to a temp file that is deleted after the run, not into run.mjs
  const varsFile = path.join(os.tmpdir(), `dr-vars-${process.pid}-${Date.now()}.json`).replace(/\\/g, "/");
  fs.writeFileSync(varsFile, JSON.stringify(opt.vars));
  fs.writeFileSync(runFile, `// generated by demo-recorder cli
import { run } from ${JSON.stringify(pathToFileURL(`${HERE}/recorder/runner.mjs`).href)};
await run({
  g: { taskSpace, listTaskSpaces, claimTaskSpace, takeOverTaskSpace },
  scenarioPath: ${JSON.stringify(scPath)},
  outDir: ${JSON.stringify(out)},
  mode: ${JSON.stringify(cmd)},
  spaceId: ${opt.space ?? null},
  vars: JSON.parse((await import("node:fs")).readFileSync(${JSON.stringify(varsFile)}, "utf8")),
  from: ${JSON.stringify(opt.from ?? null)},
});
`);
  if (cmd === "record") console.log("녹화 중에는 ego 창을 화면 앞에 두고 가리거나 최소화하지 마세요.");
  let code;
  try {
    code = runEgo(runFile);
  } finally {
    fs.rmSync(varsFile, { force: true });
  }
  console.log(`출력 폴더: ${out}`);
  process.exit(code);
} else if (cmd === "finish") {
  const id = Number(target);
  const out = `${OUT_ROOT}/_finish-${id}.mjs`;
  fs.mkdirSync(OUT_ROOT, { recursive: true });
  fs.writeFileSync(out, `const task = await taskSpace(${id});\nawait task.finish({ keep: [] });\nconsole.log("finished ${id}");\n`);
  process.exit(runEgo(out));
} else {
  console.log("사용법: node cli.mjs validate|dry|record <scenario.mjs> [--var k=v] [--space id] [--out dir] | finish <spaceId>");
  process.exit(2);
}
